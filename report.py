"""
report.py
---------
MODULE: Automated Report Generation
INPUT:  the results of one analysis (assessments, health score, priority)
        plus optional historical-comparison / before-after-comparison data
OUTPUT: a structured report dict, and three renderings of it: JSON
        (machine-readable), HTML (viewable in-browser), and PDF (a
        formatted inspection-style document)
WHY:    turns an in-memory analysis result into an artifact the user can
        save, print, or hand to someone else
ALGORITHM: no scoring logic lives here - this module only formats data
        computed by severity.py / health_score.py / history.py / comparison.py
INTERACTION: called once per `/analyze` (and once per before/after run) in
        app.py, right after the pipeline finishes.
"""

from __future__ import annotations

import json
import time
import uuid
from typing import List, Optional

from jinja2 import Environment, FileSystemLoader, select_autoescape
from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.units import inch
from reportlab.platypus import (SimpleDocTemplate, Table, TableStyle, Paragraph,
                                 Spacer, Image as RLImage)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

from severity import DamageAssessment, PriorityResult
from health_score import HealthResult


def new_inspection_id() -> str:
    return f"INS-{time.strftime('%Y%m%d')}-{uuid.uuid4().hex[:6].upper()}"


def build_report_dict(image_name: str, assessments: List[DamageAssessment],
                       health: HealthResult, priority: PriorityResult,
                       location: Optional[str] = None,
                       detector_backend: str = "unknown",
                       is_primary_detector: bool = False,
                       history_comparison: Optional[dict] = None,
                       repair_comparison: Optional[dict] = None,
                       inspection_id: Optional[str] = None) -> dict:
    return {
        "project_title": "Roadscan - AI Road Damage Assessment System",
        "inspection_id": inspection_id or new_inspection_id(),
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
        "image_name": image_name,
        "location": location,
        "detector_backend": detector_backend,
        "detector_is_primary_yolov7": is_primary_detector,
        "num_damages_detected": len(assessments),
        "damages": [
            {
                "detection_id": i + 1,
                "class_id": a.detection.class_id,
                "class_name": a.detection.class_name,
                "confidence": round(a.detection.confidence, 3),
                "bbox": a.detection.bbox,
                "severity": a.severity,
                "severity_score": a.severity_score,
                "reason": a.reason,
                "estimated_area_ratio": round(a.area_ratio, 4),
            }
            for i, a in enumerate(assessments)
        ],
        "road_health_score": health.score,
        "road_condition": health.condition,
        "health_score_breakdown": health.breakdown,
        "penalty_by_class": health.penalty_by_class,
        "repair_priority": priority.level,
        "priority_reason": priority.reason,
        "recommended_action": priority.recommended_action,
        "history_comparison": history_comparison,
        "repair_comparison": repair_comparison,
        "disclaimer": (
            "This report is generated by an automated image-based decision-support tool. "
            "It is not a certified civil-engineering inspection and should be verified by a "
            "qualified professional before any repair decision is finalized."
        ),
    }


def save_json_report(report: dict, path: str):
    with open(path, "w") as f:
        json.dump(report, f, indent=2, default=str)


# ---------------------------------------------------------------------------
# HTML report
# ---------------------------------------------------------------------------

def render_html_report(report: dict, annotated_image_path: str, templates_dir: str) -> str:
    env = Environment(loader=FileSystemLoader(templates_dir), autoescape=select_autoescape(["html"]))
    template = env.get_template("report.html")
    return template.render(report=report, annotated_image_path=annotated_image_path)


def save_html_report(report: dict, annotated_image_url: str, templates_dir: str, path: str):
    env = Environment(loader=FileSystemLoader(templates_dir), autoescape=select_autoescape(["html"]))
    template = env.get_template("report.html")
    html = template.render(report=report, annotated_image_url=annotated_image_url, standalone=True)
    with open(path, "w") as f:
        f.write(html)


# ---------------------------------------------------------------------------
# PDF report
# ---------------------------------------------------------------------------

def save_pdf_report(report: dict, annotated_image_path: str, pdf_path: str):
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("TitleX", parent=styles["Title"], fontSize=18)
    h2 = styles["Heading2"]
    normal = styles["BodyText"]
    small = ParagraphStyle("Small", parent=styles["BodyText"], fontSize=8, textColor=colors.grey)

    doc = SimpleDocTemplate(pdf_path, pagesize=letter, topMargin=0.6 * inch, bottomMargin=0.6 * inch)
    story = []

    story.append(Paragraph(report["project_title"], title_style))
    story.append(Paragraph("Road Damage Inspection Report", h2))
    story.append(Spacer(1, 4))
    meta = [
        ["Inspection ID", report["inspection_id"]],
        ["Date / time", report["timestamp"]],
        ["Image", report["image_name"]],
        ["Location", report.get("location") or "(not specified)"],
        ["Detection backend", f"{report['detector_backend']} "
         f"({'PRIMARY - YOLOv7' if report['detector_is_primary_yolov7'] else 'FALLBACK - classical CV, not a trained model'})"],
    ]
    mt = Table(meta, colWidths=[1.6 * inch, 4.1 * inch])
    mt.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("TEXTCOLOR", (0, 0), (0, -1), colors.grey),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ]))
    story.append(mt)
    story.append(Spacer(1, 10))

    try:
        img = RLImage(annotated_image_path, width=5.5 * inch, height=3.6 * inch, kind="proportional")
        story.append(img)
        story.append(Spacer(1, 12))
    except Exception:
        pass

    story.append(Paragraph("Summary", h2))
    summary_data = [
        ["Road Health Score", f"{report['road_health_score']} / 100"],
        ["Condition", report["road_condition"]],
        ["Damages Detected", str(report["num_damages_detected"])],
        ["Repair Priority", report["repair_priority"]],
    ]
    t = Table(summary_data, colWidths=[2.2 * inch, 3.5 * inch])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#eef2f7")),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("FONTSIZE", (0, 0), (-1, -1), 10),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(t)
    story.append(Spacer(1, 14))

    if report.get("penalty_by_class"):
        story.append(Paragraph("Health-Score Penalty Breakdown", h2))
        rows = [["Damage type", "Penalty"]]
        for cls, pen in report["penalty_by_class"].items():
            rows.append([cls, f"-{pen}"])
        pt = Table(rows, colWidths=[3.5 * inch, 2.2 * inch])
        pt.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#334155")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
        ]))
        story.append(pt)
        story.append(Spacer(1, 14))

    story.append(Paragraph("Detected Damage", h2))
    if report["damages"]:
        rows = [["#", "Type", "Confidence", "Severity", "Est. Area %"]]
        for d in report["damages"]:
            rows.append([
                str(d["detection_id"]),
                f"{d['class_id']} - {d['class_name']}",
                f"{d['confidence']*100:.0f}%",
                d["severity"],
                f"{d['estimated_area_ratio']*100:.2f}%",
            ])
        dt = Table(rows, colWidths=[0.35 * inch, 2.35 * inch, 1.0 * inch, 1.0 * inch, 1.0 * inch])
        dt.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#334155")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
        ]))
        story.append(dt)
        story.append(Spacer(1, 8))
        for d in report["damages"]:
            story.append(Paragraph(f"<b>#{d['detection_id']} {d['class_name']}</b> - {d['reason']}", small))
    else:
        story.append(Paragraph("No damage detected.", normal))
    story.append(Spacer(1, 14))

    story.append(Paragraph("Repair Priority", h2))
    story.append(Paragraph(f"<b>{report['repair_priority']}</b> - {report['priority_reason']}", normal))
    story.append(Spacer(1, 6))
    story.append(Paragraph("Recommended action: " + report["recommended_action"], normal))
    story.append(Spacer(1, 14))

    if report.get("history_comparison"):
        hc = report["history_comparison"]
        story.append(Paragraph("Historical Comparison", h2))
        story.append(Paragraph(
            f"Trend: <b>{hc['trend_status'].upper()}</b>. Health score change: {hc['score_delta']:+.1f}. "
            f"Damage count change: {hc['count_delta']:+d}.", normal))
        story.append(Spacer(1, 14))

    if report.get("repair_comparison"):
        rc = report["repair_comparison"]
        story.append(Paragraph("Before / After Comparison", h2))
        story.append(Paragraph(f"<b>{rc['verdict']}</b> - {rc['explanation']}", normal))
        story.append(Spacer(1, 14))

    story.append(Paragraph("Disclaimer", h2))
    story.append(Paragraph(report["disclaimer"], normal))

    doc.build(story)
